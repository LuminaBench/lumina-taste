#!/usr/bin/env node
// Builds the showcase gallery (preview/dist) from the component, chart and blueprint sources.
// 1. expands icon placeholders, 2. writes a generated registry, 3. bundles with esbuild.
import { build } from 'esbuild';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const gen = join(root, 'preview/generated');
const dist = join(root, 'preview/dist');
execFileSync(process.execPath, [join(root, 'scripts/expand-icons.mjs')], { stdio: 'inherit' });
mkdirSync(gen, { recursive: true });

const rel = (p) => './' + relative(gen, p).split('\\').join('/');
const families = readdirSync(join(root, 'components/ui'))
  .filter((d) => existsSync(join(root, 'components/ui', d, 'family.json')))
  .map((d) => ({ dir: d, ...JSON.parse(readFileSync(join(root, 'components/ui', d, 'family.json'), 'utf8')) }))
  .sort((a, b) => a.order - b.order);

let imports = '';
let entries = '';
let i = 0;
const missing = [];
for (const fam of families) {
  for (const c of fam.components) {
    const dir = join(root, 'components/ui', fam.dir, c.id);
    const html = join(dir, `${c.id}.html`);
    if (!existsSync(html)) { missing.push(c.id); continue; }
    const v = `c${i++}`;
    imports += `import ${v}h from '${rel(html)}';\n`;
    if (existsSync(join(dir, `${c.id}.css`))) imports += `import '${rel(join(dir, `${c.id}.css`))}';\n`;
    const hasTs = existsSync(join(dir, `${c.id}.ts`));
    if (hasTs) imports += `import { enhance as ${v}e } from '${rel(join(dir, c.id))}';\n`;
    entries += `  { ...${JSON.stringify({ ...c, family: fam.dir, familyTitle: fam.title })}, html: ${v}h, enhance: ${hasTs ? `${v}e` : 'null'} },\n`;
  }
}
const familyList = JSON.stringify(families.map(({ dir, title, summary }) => ({ id: dir, title, summary })));

// Charts registry (components/charts/<id>/meta.json)
let chartImports = '';
let chartEntries = '';
const chartsDir = join(root, 'components/charts');
if (existsSync(chartsDir)) {
  const metas = readdirSync(chartsDir)
    .filter((d) => existsSync(join(chartsDir, d, 'meta.json')))
    .map((d) => ({ dir: d, ...JSON.parse(readFileSync(join(chartsDir, d, 'meta.json'), 'utf8')) }))
    .sort((a, b) => a.order - b.order);
  metas.forEach((m, k) => {
    chartImports += `import * as k${k} from '${rel(join(chartsDir, m.dir, m.dir))}';\n`;
    chartEntries += `  { meta: ${JSON.stringify(m)}, mod: k${k} },\n`;
  });
}

// Blueprints (blueprints/<id>/meta.json)
const bpDir = join(root, 'blueprints');
const blueprints = existsSync(bpDir)
  ? readdirSync(bpDir).filter((d) => existsSync(join(bpDir, d, 'meta.json'))).map((d) => JSON.parse(readFileSync(join(bpDir, d, 'meta.json'), 'utf8'))).sort((a, b) => a.order - b.order)
  : [];

// Styles atlas (tokens/styles/source.json)
const stylesPath = join(root, 'tokens/styles/source.json');
const styles = existsSync(stylesPath) ? JSON.parse(readFileSync(stylesPath, 'utf8')).styles : [];
const comparePath = join(root, 'components/ui/compare.json');
const compare = existsSync(comparePath) ? JSON.parse(readFileSync(comparePath, 'utf8')) : { intro: '', pairs: [] };

writeFileSync(
  join(gen, 'registry.ts'),
  `// Generated by scripts/build.mjs. Do not edit.\n/* eslint-disable */\n${imports}${chartImports}\nexport const FAMILIES = ${familyList};\nexport const UI: any[] = [\n${entries}];\nexport const CHARTS: any[] = [\n${chartEntries}];\nexport const BLUEPRINTS: any[] = ${JSON.stringify(blueprints)};\nexport const STYLES: any[] = ${JSON.stringify(styles)};\nexport const COMPARE: { intro: string; pairs: Array<{ id: string; title: string; ids: string[]; rule: string; use: Record<string, string> }> } = ${JSON.stringify(compare)};\n`,
);
if (missing.length) console.warn(`Not yet implemented: ${missing.join(', ')}`);

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
const common = { bundle: true, format: 'esm', target: 'es2022', loader: { '.html': 'text' }, minify: true, legalComments: 'none', logLevel: 'warning', jsx: 'automatic' };
await build({ ...common, entryPoints: { gallery: join(root, 'preview/gallery.ts') }, outdir: dist });
cpSync(join(root, 'preview/index.html'), join(dist, 'index.html'));

// Component sources, fetched on demand by the element page's Code tabs (never bundled).
for (const fam of families) for (const c of fam.components) {
  const from = join(root, 'components/ui', fam.dir, c.id);
  if (!existsSync(from)) continue;
  const to = join(dist, 'src', c.id);
  mkdirSync(to, { recursive: true });
  for (const ext of ['html', 'css', 'ts', 'react.tsx']) {
    const f = join(from, `${c.id}.${ext}`);
    if (existsSync(f)) writeFileSync(join(to, `${c.id}.${ext}.txt`), readFileSync(f, 'utf8'));
  }
}

// Blueprints: each is a standalone page bundled with its own CSS + TS.
for (const bp of blueprints) {
  const src = join(bpDir, bp.id);
  const out = join(dist, 'blueprints', bp.id);
  mkdirSync(out, { recursive: true });
  await build({ ...common, entryPoints: { main: join(src, 'main.ts') }, outdir: out });
  const page = readFileSync(join(src, 'index.html'), 'utf8').replace(/<script type="module" src="\.\/main\.ts"><\/script>/, '<link rel="stylesheet" href="./main.css"><script type="module" src="./main.js"></script>');
  writeFileSync(join(out, 'index.html'), page);
}

// React harness used by the test suite (not part of the hosted gallery).
if (existsSync(join(root, 'tests/react/harness.tsx'))) {
  await build({ ...common, entryPoints: { harness: join(root, 'tests/react/harness.tsx') }, outdir: join(dist, '_react') });
  writeFileSync(join(dist, '_react/index.html'), `<!doctype html><html lang="en" data-palette="slate-forest" data-mode="light" data-type="precision" data-density="balanced" data-radius="balanced" data-motion="snappy"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>React harness</title><link rel="stylesheet" href="./harness.css"></head><body><div id="root"></div><script type="module" src="./harness.js"></script></body></html>`);
}
console.log(`Built gallery: ${entries.split('\n').length - 1} UI patterns, ${chartEntries.split('\n').length - 1} charts, ${blueprints.length} blueprints → preview/dist`);
